#!/usr/bin/env python3
"""Generate Compose vectors from the Iconsax paths integrated into TeleDrive."""
from argparse import ArgumentParser
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/iconsax"
COMPOSE = ROOT / "skin/src/commonMain/kotlin/app/tgdrive/ui/DriveIcons.kt"
NOTICE = ROOT / "app/src/main/assets/licenses/Iconsax-NOTICE.txt"

HEADER = """// Generated by scripts/generate_icons.py. Source and terms are in third_party/iconsax.
// Icon assets from Iconsax - https://iconsax.io (Proprietary Free License).
package app.tgdrive.ui

import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp
"""

RENDERER = """private class IconVariants(outline: () -> ImageVector, broken: () -> ImageVector) {
    private val outlineVector by lazy(outline)
    private val brokenVector by lazy(broken)

    @Composable
    fun current(): ImageVector = when (LocalIconStyle.current) {
        IconStyle.Outline -> outlineVector
        IconStyle.Broken -> brokenVector
    }
}

private fun vector(
    name: String,
    paths: ImageVector.Builder.() -> Unit
): ImageVector = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply(paths).build()

private val glyphColor = SolidColor(Color.Black)

private fun ImageVector.Builder.filled(data: String) {
    addPath(PathParser().parsePathString(data).toNodes(), fill = glyphColor)
}

private fun ImageVector.Builder.stroked(
    width: Float,
    data: String,
    cap: StrokeCap = StrokeCap.Butt,
    join: StrokeJoin = StrokeJoin.Miter,
    miter: Float = 4f
) {
    addPath(
        PathParser().parsePathString(data).toNodes(),
        stroke = glyphColor,
        strokeLineWidth = width,
        strokeLineCap = cap,
        strokeLineJoin = join,
        strokeLineMiter = miter
    )
}
"""


def kotlin_name(icon):
    return "icon" + "".join(part.title() for part in icon.split("-"))


def emit_vector(style, icon, paths, suffix=""):
    yield f'        {style} = {{ vector("iconsax:{style}/{icon}") {{'
    for path in paths:
        data = json.dumps(path["d"])
        if "strokeWidth" in path:
            attributes = []
            if "strokeLineCap" in path:
                attributes.append(", cap = StrokeCap.Round")
            if "strokeLineJoin" in path:
                attributes.append(", join = StrokeJoin.Round")
            if "strokeMiterLimit" in path:
                attributes.append(f', miter = {path["strokeMiterLimit"]:g}f')
            yield f'            stroked({path["strokeWidth"]:g}f, {data}{"".join(attributes)})'
        else:
            yield f"            filled({data})"
    yield "        } }" + suffix


def generate(data):
    groups, site, geometry = (data[key] for key in ("app", "site", "geometry"))
    names = {icon for aliases in groups.values() for icon in aliases.values()}
    if set(geometry["outline"]) != names | set(site.values()) or set(geometry["broken"]) != names:
        raise ValueError("Every icon must have exactly the geometry used by TeleDrive")
    for variants in geometry.values():
        for icon, paths in variants.items():
            if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", icon) or not paths:
                raise ValueError(f"Invalid icon name or empty path list: {icon}")
            for path in paths:
                if not re.fullmatch(r"[Mm][A-Za-z0-9., +\-]+", path["d"]):
                    raise ValueError(f"Invalid path data for {icon}")
                attributes = {"strokeWidth": (1.5, 2), "strokeLineCap": ("round",),
                              "strokeLineJoin": ("round",), "strokeMiterLimit": (10,)}
                if any(key != "d" and value not in attributes.get(key, ()) for key, value in path.items()):
                    raise ValueError(f"Unsupported path attributes for {icon}")
    yield HEADER
    for group, aliases in groups.items():
        yield f"object {group} {{"
        for alias, icon in aliases.items():
            yield f"    val {alias}: ImageVector @Composable get() = IconsaxVectors.{kotlin_name(icon)}.current()"
        yield "}\n"
    yield "private object IconsaxVectors {"
    for icon in sorted(names):
        yield f"    val {kotlin_name(icon)} = IconVariants("
        yield from emit_vector("outline", icon, geometry["outline"][icon], suffix=",")
        yield from emit_vector("broken", icon, geometry["broken"][icon])
        yield "    )\n"
    yield "}\n"
    yield RENDERER


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files without writing them")
    args = parser.parse_args()
    data = json.loads((SOURCE / "teledrive-icons.json").read_text())
    outputs = {COMPOSE: "\n".join(generate(data)), NOTICE: (SOURCE / "NOTICE.txt").read_text()}
    for target, contents in outputs.items():
        if args.check:
            if not target.is_file() or target.read_text() != contents:
                parser.exit(1, f"{target.relative_to(ROOT)} is out of date. Run {Path(__file__).name}.\n")
        else:
            target.write_text(contents)
    print(f"{('Verified' if args.check else 'Generated')} Iconsax Outline and Broken vectors and notice.")


if __name__ == "__main__":
    main()
